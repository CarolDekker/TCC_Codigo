# Função para realizar a busca semântica
def busca_semantica(query):
    # Gera as embeddings para a query
    query_embedding = model.encode(query, convert_to_tensor=True)

    # Gera as embeddings para os textos (título e conteúdo)
    text_embeddings = model.encode(df_copia['texto'].tolist(), convert_to_tensor=True)

    # Calcula a similaridade coseno entre a query e os textos
    cosine_scores = util.pytorch_cos_sim(query_embedding, text_embeddings)[0]

    # Obtém o número máximo de resultados que podemos retornar
    num_results = min(10, len(cosine_scores))  # Ajusta para não exceder o número de entradas

    # Obtém os índices das melhores correspondências
    top_results = np.argpartition(-cosine_scores.numpy(), range(num_results))[:num_results]

    # Ordena os resultados para obter os scores mais altos
    top_results = top_results[np.argsort(-cosine_scores.numpy()[top_results])]

    resultados = []
    print("\nTop resultados para a consulta:", query)
    for idx in top_results:
        resultado = {
            'score': cosine_scores[idx].item(),  # Converte tensor para valor numérico
            'titulo': df['title'].iloc[idx],
            'texto': df['summary'].iloc[idx],
            'link': df['link'].iloc[idx]
        }
        resultados.append(resultado)

    return resultados  # Retorna a lista de resultados

