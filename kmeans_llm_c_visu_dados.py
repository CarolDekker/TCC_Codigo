def get_top_5_closest_to_centroid(df_pca_3d, original_df, cluster_column="cluster", n_closest=5):
    """
    Retorna as N ideias mais próximas do centróide de cada cluster.

    Args:
        df_pca_3d (pandas.DataFrame): DataFrame contendo as componentes principais e os clusters.
        original_df (pandas.DataFrame): DataFrame original contendo as informações das ideias.
        cluster_column (str): Nome da coluna que identifica os clusters.
        n_closest (int): Número de ideias mais próximas do centróide a serem retornadas.

    Returns:
        dict: Dicionário onde as chaves são os clusters e os valores são DataFrames com as N ideias mais próximas.
    """
    resultados = {}

    # Certificar-se de que os índices estão alinhados
    original_df = original_df.reset_index(drop=True)
    df_pca_3d = df_pca_3d.reset_index(drop=True)

    # Iterar sobre os clusters únicos
    for cluster in df_pca_3d[cluster_column].unique():
        # Filtrar o DataFrame pelo cluster atual
        df_cluster = df_pca_3d[df_pca_3d[cluster_column] == cluster]

        # Calcular o centróide do cluster
        centroid = df_cluster[["comp1", "comp2", "comp3"]].mean().values

        # Calcular a distância de cada ponto ao centróide
        df_cluster = df_cluster.copy()  # Evitar SettingWithCopyWarning
        df_cluster["distance_to_centroid"] = df_cluster.apply(
            lambda row: np.linalg.norm(row[["comp1", "comp2", "comp3"]].values - centroid),
            axis=1
        )

        # Selecionar as N ideias mais próximas
        closest_points = df_cluster.nsmallest(n_closest, "distance_to_centroid")

        # Recuperar as informações correspondentes do DataFrame original
        closest_ideas = original_df.loc[closest_points.index]

        # Salvar no dicionário
        resultados[cluster] = closest_ideas

    return resultados

