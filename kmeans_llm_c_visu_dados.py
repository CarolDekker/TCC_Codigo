# Baixar as stopwords da biblioteca nltk
nltk.download('stopwords')
stopwords_nltk = set(stopwords.words('english'))  # Ajuste o idioma conforme necessário, por exemplo, 'portuguese'

def limpar_texto(texto, stopwords, min_caracteres=3):
    """
    Remove palavras ruído de um texto.

    Args:
        texto (str): Texto original.
        stopwords (set): Conjunto de palavras a serem removidas.
        min_caracteres (int): Número mínimo de caracteres para manter uma palavra.

    Returns:
        str: Texto limpo.
    """
    if not isinstance(texto, str):
        return ""  # Retorna vazio se o texto não for uma string

    # Remove caracteres especiais, números e transforma em minúsculas
    texto = re.sub(r"[^\w\s]", "", texto).lower()

    # Filtra as palavras removendo as que estão em stopwords ou têm poucos caracteres
    palavras = texto.split()
    palavras_filtradas = [
        palavra for palavra in palavras
        if palavra not in stopwords and len(palavra) >= min_caracteres
    ]

    return " ".join(palavras_filtradas)

def gerar_nuvem_palavras_por_cluster(df, min_caracteres=3):
    """
    Gera e exibe uma nuvem de palavras para cada cluster no DataFrame.

    Args:
        df (pandas.DataFrame): DataFrame contendo as colunas 'texto' e 'cluster'.
        min_caracteres (int): Número mínimo de caracteres para manter uma palavra.
    """
    # Verifica se as colunas necessárias existem
    if 'texto' not in df.columns or 'cluster' not in df.columns:
        print("O DataFrame deve conter as colunas 'texto' e 'cluster'.")
        return

    clusters_unicos = df['cluster'].dropna().unique()
    for cluster in clusters_unicos:
        # Filtrar o DataFrame para o cluster atual e remover NaN
        textos_cluster = df[df['cluster'] == cluster]['texto'].dropna()

        # Manter apenas os valores que são strings e limpar o texto
        textos_filtrados = textos_cluster[textos_cluster.apply(lambda x: isinstance(x, str))]
        textos_limpos = textos_filtrados.apply(lambda x: limpar_texto(x, stopwords_nltk, min_caracteres))

        # Concatenar todos os textos do cluster
        texto_unico = " ".join(textos_limpos)

        # Verificar se há texto para gerar a nuvem
        if texto_unico.strip():
            # Gerar a nuvem de palavras
            wordcloud = WordCloud(
                width=800,
                height=400,
                background_color='white',
                max_words=200,
                contour_width=3,
                contour_color='steelblue',
                collocations=False
            ).generate(texto_unico)

            # Mostrar a nuvem de palavras
            plt.figure(figsize=(10, 5))
            plt.imshow(wordcloud, interpolation='bilinear')
            plt.axis('off')
            plt.title(f"Nuvem de Palavras para o Cluster {cluster}", fontsize=16)
            plt.show()
        else:
            print(f"Cluster {cluster} não possui textos válidos para gerar uma nuvem.")

