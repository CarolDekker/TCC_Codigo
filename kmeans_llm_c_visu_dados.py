def criar_grafo(query, resultados):
    """
    Cria um grafo com a palavra pai no centro e títulos conectados com scores.

    Args:
        palavra_pai (str): A palavra central do grafo.
        lista_dados (list): Lista de dicionários com dados de títulos, scores, textos e links.

    Returns:
        G (networkx.Graph): Grafo criado.
    """
    G = nx.Graph()
    G.add_node(query, tamanho=len(query))  # Adiciona a palavra pai como nó central

    # Adiciona os títulos como nós e conecta à palavra pai com o score
    for item in resultados:
        titulo = item['titulo']
        score = item['score']
        G.add_node(titulo, texto=item['texto'], link=item['link'], tamanho=len(titulo))  # Adiciona nó com atributos
        G.add_edge(query, titulo, score=score)  # Conecta ao nó central

    return G

def desenhar_grafo(G, query):
    """
    Desenha o grafo com círculos transparentes para esconder as arestas, mantendo o texto visível.

    Args:
        G (networkx.Graph): O grafo a ser desenhado.
        query (str): A palavra central do grafo.
    """
    pos = nx.spring_layout(G)  # Layout para posicionar os nós
    plt.figure(figsize=(12, 8))

    # Tamanhos dos círculos proporcionais ao comprimento do texto (multiplicador para escala maior)
    fator_escala = 150  # Ajuste para círculos maiores
    tamanhos = [G.nodes[node]['tamanho'] * fator_escala for node in G.nodes]

    # Desenha os nós com transparência
    nx.draw_networkx_nodes(
        G, pos, node_color="lightblue", node_size=tamanhos, alpha=0.3
    )

    # Desenha as arestas
    nx.draw_networkx_edges(G, pos, width=1.5, alpha=0.7, edge_color="gray")

    # Adiciona rótulos aos nós
    node_labels = {node: node for node in G.nodes}
    nx.draw_networkx_labels(G, pos, labels=node_labels, font_size=10)

    # Adiciona rótulos às arestas (scores)
    edge_labels = {(u, v): f"{d['score']:.2f}" for u, v, d in G.edges(data=True)}
    nx.draw_networkx_edge_labels(G, pos, edge_labels=edge_labels, font_color="red")

    # Título geral
    plt.title(f"Grafo para '{query}'", fontsize=16)
    plt.axis("off")
    plt.show()

